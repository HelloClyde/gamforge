"""Deterministic 3:2 picture LUTs: four columns in two 1-bpp rows.

Quantize only after both dimensions are interpolated; no intermediate
horizontal rounding. Coordinates use pixel centers, with clamped borders.
The optional sharp kernel integrates source pixel areas instead of extending
the bilinear footprint into neighbouring pixels. Both kernels quantize only
once. Sharp single-row phases use one byte lookup; its mixed phase uses two
nibble-pair lookups. The C preprocessor selects only the required table set.
"""


def triplet_tables(*, sharp: bool = False) -> list[list[int]]:
    result = []
    weights = (6, 3, 0) if sharp else (5, 3, 1)
    for wy in weights:  # lower row weights /6 for output phases 0,1,2
        table = []
        for index in range(256):
            upper, lower = index >> 4, index & 15
            word = 0
            for pair, wx in enumerate(weights):
                # Four bits are [previous odd, even, odd, next even].
                upper_black = ((upper >> (3 - pair)) & 1) * (6 - wx)
                upper_black += ((upper >> (2 - pair)) & 1) * wx
                lower_black = ((lower >> (3 - pair)) & 1) * (6 - wx)
                lower_black += ((lower >> (2 - pair)) & 1) * wx
                white_weight = 36 - upper_black * (6 - wy) - lower_black * wy
                word = (word << 2) | ((white_weight + 6) // 12)
            table.append(word)
        result.append(table)
    return result


def packed_column_tables(*, sharp: bool = False) -> list[list[list[int]]]:
    """Pre-position triplets in a little-endian 12-pixel packed column.

    Four lookups can then be ORed directly: no per-column bit permutation.
    This is a 12 KiB read-only table, not an allocation or per-game cache.
    """
    result = []
    for phase in triplet_tables(sharp=sharp):
        positions = []
        for start in (0, 3, 6, 9):
            entries = []
            for index in range(256):
                upper = sum(((index >> (7 - p * 2)) & 1) << (3 - p) for p in range(4))
                lower = sum(((index >> (6 - p * 2)) & 1) << (3 - p) for p in range(4))
                triplet = phase[upper * 16 + lower]
                word = 0
                for pixel in range(3):
                    color = (triplet >> (4 - pixel * 2)) & 3
                    at = start + pixel
                    word |= color << ((at // 4) * 8 + 6 - (at % 4) * 2)
                entries.append(word)
            positions.append(entries)
        result.append(positions)
    return result


def sharp_byte_tables() -> tuple[list[int], list[list[int]]]:
    """Exact pixel-area coverage in 3 KiB, already packed for LCD writes.

    Phase 0 selects the lower row and phase 2 the upper row. A complete
    source byte becomes twelve pixels with one lookup. Phase 1 averages two
    rows: each table sees four upper/lower bits and emits six pixels at its
    final offset. Rounding happens once, after all contributing pixels.
    """

    def pack(upper, lower, count, start):
        word = 0
        for pair in range(count // 2):
            shift = count - 2 - pair * 2
            a, b = (upper >> (shift + 1)) & 1, (upper >> shift) & 1
            c, d = (lower >> (shift + 1)) & 1, (lower >> shift) & 1
            for position, black in enumerate((2 * (a + c), a + b + c + d, 2 * (b + d))):
                color = ((4 - black) * 3 + 2) // 4
                at = start + pair * 3 + position
                word |= color << ((at // 4) * 8 + 6 - (at % 4) * 2)
        return word

    single = [pack(bits, bits, 8, 0) for bits in range(256)]
    mixed = [[pack(index >> 4, index & 15, 4, start) for index in range(256)] for start in (0, 6)]
    return single, mixed


def _lut_lines(*, sharp: bool) -> list[str]:
    lines = ["static const c6502_u32 c6502_linear_lut[3][1024] = {"]
    for phase in packed_column_tables(sharp=sharp):
        lines.append("    {")
        for table in phase:
            for start in range(0, 256, 8):
                lines.append(
                    "        " + ",".join(f"0x{v:06x}" for v in table[start : start + 8]) + ","
                )
        lines.append("    },")
    lines.extend(["};", ""])
    return lines


def lut_header() -> str:
    lines = [
        "/* Generated by a9288.compiler.linear.lut_header; tested against the generator.",
        " * SHARP: 3 KiB; bilinear: 12 KiB + 512-byte spread table. No initialization.",
        " * SHARP: pixel-area coverage; default: pixel-centred bilinear. */",
        "#if defined(C6502_T_FILTER_SHARP)",
    ]
    single, mixed = sharp_byte_tables()
    for name, values in (("c6502_sharp_single", single),):
        lines.append(f"static const c6502_u32 {name}[256] = {{")
        for start in range(0, 256, 8):
            lines.append("    " + ",".join(f"0x{v:06x}" for v in values[start : start + 8]) + ",")
        lines.extend(["};", ""])
    lines.append("static const c6502_u32 c6502_sharp_mixed[2][256] = {")
    for values in mixed:
        lines.append("    {")
        for start in range(0, 256, 8):
            lines.append(
                "        " + ",".join(f"0x{v:06x}" for v in values[start : start + 8]) + ","
            )
        lines.append("    },")
    lines.extend(["};", ""])
    lines.append("#else")
    lines.extend(_lut_lines(sharp=False))
    lines.append("")
    lines.append("/* Spread source bits into two-bit (upper,lower) sample lanes. */")
    lines.append("static const c6502_u16 c6502_linear_spread[256] = {")
    spread = [sum(((v >> p) & 1) << (p * 2) for p in range(8)) for v in range(256)]
    for start in range(0, 256, 8):
        lines.append("    " + ",".join(f"0x{v:04x}" for v in spread[start : start + 8]) + ",")
    lines.extend(["};", ""])
    lines.extend(["#endif", ""])
    return "\n".join(lines)
