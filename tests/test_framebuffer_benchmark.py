"""Contracts for the synthetic, firmware-independent CPU framebuffer probe."""

import hashlib
import runpy
from pathlib import Path

import pytest

BENCH = runpy.run_path(
    str(Path(__file__).resolve().parents[1] / "scripts/benchmark_9288t_framebuffer.py")
)
reference_frame = BENCH["reference_frame"]


def pixel(frame, x, y):
    return (frame[y * 60 + x // 4] >> (6 - (x & 3) * 2)) & 3


@pytest.mark.parametrize(
    "scenario,sha256",
    [
        ("text24", "38b0155dee16c70fd05ef39042ccade167ba75a893687d0471277c384f09b1a4"),
        ("text12", "c5ddf4f06ada18f4414c1eab5b96a72b39f070c9105f143e3dd2796bc8370a5f"),
        ("text_redraw", "a3d15d03dd95b6b2ae82135def52caaa8e4d2608b8fdda830588d91dad9f2a04"),
    ],
)
def test_text_oracles_match_verified_baseline_s1c33_object(scenario, sha256):
    # Captured by the actual release runtime.o, not generated by a host C copy.
    first = reference_frame(scenario, 1, "1.5x-sharp", True)
    assert hashlib.sha256(first).hexdigest() == sha256
    assert reference_frame(scenario, 9, "1.5x-sharp", True) == first
    assert reference_frame(scenario, 2, "1.5x-sharp", True) != first


@pytest.mark.parametrize("scale", ["1.5x-linear", "1.5x-sharp"])
@pytest.mark.parametrize(
    "scenario,left,top,width", [("text24", 11, 32, 24), ("text12", 14, 56, 12)]
)
def test_text_probe_uses_unfiltered_target_resolution_glyphs(scale, scenario, left, top, width):
    frame = reference_frame(scenario, 1, scale, True)
    inverse = reference_frame(scenario, 2, scale, True)
    # First fixed target byte is 0x11, next row 0x2e. These marks are
    # intentionally not nearest-neighbour copies of the guest 16-high glyph.
    assert [pixel(frame, left + x, top) for x in range(8)] == [3, 3, 3, 0, 3, 3, 3, 0]
    assert [pixel(frame, left + x, top + 1) for x in range(8)] == [3, 3, 0, 3, 0, 0, 0, 3]
    for y in range(top, top + 24):
        for x in range(left, left + width):
            assert pixel(frame, x, y) in (0, 3)
            assert pixel(frame, x, y) + pixel(inverse, x, y) == 3
    assert all(pixel(frame, 239, y) == 3 for y in range(160))


def test_bitmap_over_text_erases_only_covered_part_and_exposes_grays():
    text = reference_frame("text24", 1, "1.5x-sharp", True)
    redraw = reference_frame("text_redraw", 1, "1.5x-sharp", True)
    for y in range(32, 56):
        for x in range(11, 24):
            assert pixel(text, x, y) == pixel(redraw, x, y)
    assert {pixel(redraw, x, y) for y in range(32, 56) for x in range(24, 35)} == {0, 1, 2, 3}
    assert text != redraw
